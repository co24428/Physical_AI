-- SynapseQC 지식베이스(RAG): 레포 문서 + 웹 페이지 문구
-- 기존 documents/chunks(더미, 사용자별 RLS)와 분리된 공개 지식베이스.
-- 임베딩: gemini-embedding-2, 768 dims (rag-answer 함수와 동일)
-- 적재/임베딩: Edge Function kb-ingest (rag/ingest.py), 검색: Edge Function kb-search

create table public.kb_documents (
  id bigint generated by default as identity primary key,
  source_key text not null unique,          -- 레포 내 경로 (예: report/data_preprocessing.md)
  source_type text not null check (source_type in ('prd', 'report', 'web')),
  title text not null,
  url text,                                  -- GitHub 원문 또는 GitHub Pages 주소
  content_hash text not null,                -- 원문 sha256, 바뀐 문서만 다시 적재
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.kb_chunks (
  id bigint generated by default as identity primary key,
  document_id bigint not null references public.kb_documents (id) on delete cascade,
  chunk_index int not null,
  heading_path text not null default '',     -- 예: "3. B단계 > B3. ROI 검출"
  content text not null,
  embedding extensions.vector(768),          -- null 이면 kb-ingest 함수(action: embed)가 채운다
  fts tsvector generated always as (to_tsvector('simple', heading_path || ' ' || content)) stored,
  created_at timestamptz not null default now(),
  unique (document_id, chunk_index)
);

create index kb_chunks_embedding_hnsw_idx
  on public.kb_chunks using hnsw (embedding extensions.vector_cosine_ops);
create index kb_chunks_fts_idx on public.kb_chunks using gin (fts);
create index kb_chunks_pending_idx on public.kb_chunks (id) where embedding is null;

-- 공개 사이트/공개 레포 내용이므로 읽기는 누구나, 쓰기는 service role 만
alter table public.kb_documents enable row level security;
alter table public.kb_chunks enable row level security;

create policy "Public read access to kb documents"
  on public.kb_documents for select to anon, authenticated using (true);
create policy "Public read access to kb chunks"
  on public.kb_chunks for select to anon, authenticated using (true);

-- 벡터 유사도 검색
create or replace function public.match_kb_chunks(
  query_embedding extensions.vector(768),
  match_count int default 5,
  match_threshold float default 0,
  source_types text[] default null
)
returns table (
  id bigint, document_id bigint, title text, url text, source_type text,
  heading_path text, content text, similarity float
)
language sql
stable
security invoker
set search_path = ''
as $$
  select c.id, d.id, d.title, d.url, d.source_type, c.heading_path, c.content,
         1 - (c.embedding operator(extensions.<=>) query_embedding) as similarity
  from public.kb_chunks c
  join public.kb_documents d on d.id = c.document_id
  where c.embedding is not null
    and (source_types is null or d.source_type = any (source_types))
    and 1 - (c.embedding operator(extensions.<=>) query_embedding) > match_threshold
  order by c.embedding operator(extensions.<=>) query_embedding
  limit match_count;
$$;

-- 하이브리드 검색 (벡터 + 키워드, Reciprocal Rank Fusion)
-- 키워드는 OR 로 묶는다: 한국어 조사 때문에 AND 면 거의 안 걸린다.
create or replace function public.hybrid_search_kb(
  query_text text,
  query_embedding extensions.vector(768),
  match_count int default 8,
  full_text_weight float default 1,
  semantic_weight float default 1,
  rrf_k int default 50,
  source_types text[] default null
)
returns table (
  id bigint, document_id bigint, title text, url text, source_type text,
  heading_path text, content text, similarity float, score float
)
language sql
stable
security invoker
set search_path = ''
as $$
  with q as (
    select nullif(replace(plainto_tsquery('simple', query_text)::text, '&', '|'), '')::tsquery as tsq
  ),
  candidates as (
    select c.id
    from public.kb_chunks c
    join public.kb_documents d on d.id = c.document_id
    where source_types is null or d.source_type = any (source_types)
  ),
  full_text as (
    select c.id,
           row_number() over (order by ts_rank_cd(c.fts, q.tsq) desc) as rank_ix
    from public.kb_chunks c, q
    where c.id in (select id from candidates) and c.fts @@ q.tsq
    order by rank_ix
    limit least(match_count, 30) * 2
  ),
  semantic as (
    select c.id,
           row_number() over (order by c.embedding operator(extensions.<=>) query_embedding) as rank_ix
    from public.kb_chunks c
    where c.id in (select id from candidates) and c.embedding is not null
    order by rank_ix
    limit least(match_count, 30) * 2
  )
  select c.id, d.id, d.title, d.url, d.source_type, c.heading_path, c.content,
         1 - (c.embedding operator(extensions.<=>) query_embedding) as similarity,
         coalesce(1.0 / (rrf_k + full_text.rank_ix), 0.0) * full_text_weight
           + coalesce(1.0 / (rrf_k + semantic.rank_ix), 0.0) * semantic_weight as score
  from full_text
  full outer join semantic on full_text.id = semantic.id
  join public.kb_chunks c on c.id = coalesce(full_text.id, semantic.id)
  join public.kb_documents d on d.id = c.document_id
  order by score desc
  limit least(match_count, 30);
$$;
